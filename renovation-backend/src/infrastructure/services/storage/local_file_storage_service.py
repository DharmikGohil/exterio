"""File storage on local disk, served by the API under /files.

Paths are generated by the application and contain random ids, but they are
still resolved and checked so nothing can be read or written outside the root.
"""

import shutil
from pathlib import Path

from domain.interfaces.services.file_storage_service import IFileStorageService

PUBLIC_PREFIX = "/files"


class LocalFileStorageService(IFileStorageService):
    def __init__(self, root: Path) -> None:
        self._root = root.resolve()
        self._root.mkdir(parents=True, exist_ok=True)

    @property
    def root(self) -> Path:
        return self._root

    def save(self, path: str, data: bytes) -> None:
        target = self._resolve(path)
        target.parent.mkdir(parents=True, exist_ok=True)
        temporary = target.with_suffix(target.suffix + ".tmp")
        temporary.write_bytes(data)
        temporary.replace(target)

    def read(self, path: str) -> bytes:
        return self._resolve(path).read_bytes()

    def exists(self, path: str) -> bool:
        return self._resolve(path).is_file()

    def delete(self, path: str) -> None:
        self._resolve(path).unlink(missing_ok=True)

    def delete_prefix(self, prefix: str) -> None:
        target = self._resolve(prefix)
        if target.is_dir():
            shutil.rmtree(target, ignore_errors=True)

    def url_for(self, path: str) -> str:
        return f"{PUBLIC_PREFIX}/{path.lstrip('/')}"

    def _resolve(self, path: str) -> Path:
        target = (self._root / path.lstrip("/")).resolve()
        if target != self._root and self._root not in target.parents:
            raise ValueError("Path escapes the storage root")
        return target
